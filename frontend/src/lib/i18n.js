const index = { UA: 0, CZ: 1, EN: 2 }

export function makeT(lang) {
  const i = index[lang] ?? 0
  return (key, params) => {
    const entry = dict[key]
    let text = entry ? entry[i] : key
    if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, v ?? '')
    return text
  }
}

export const hasKey = (key) => key in dict

// Вибір локалізованого поля з обʼєкта API: pick(subject, 'name') → nameUa / nameCs / nameEn
export function pick(obj, base, lang) {
  if (!obj) return ''
  const suffix = lang === 'CZ' ? 'Cs' : lang === 'EN' ? 'En' : 'Ua'
  return obj[base + suffix] || obj[base + 'Ua'] || obj[base + 'En'] || obj[base + 'Cs'] || ''
}
